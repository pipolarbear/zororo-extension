  function t(lang, key, params = {}) {
    const locale = LOCALES[lang] || LOCALES.en;
    let str = locale[key];
    if (!str) str = LOCALES.en[key] || key;
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp("\\{" + k + "\\}", "g"), v);
    }
    return str;
  }

  function detectLang() {
    let code = "";
    const pm = window.location.pathname.match(/^\/([a-z]{2}(?:-[a-z]{2})?)\/title\//i);
    if (pm) code = pm[1];
    if (!code && document.documentElement) code = document.documentElement.lang || "";
    if (!code) {
      const cm = document.cookie.match(/(?:^|;\s*)lc-main=([^;]+)/);
      if (cm) code = decodeURIComponent(cm[1]);
    }
    if (!code) code = navigator.language || "";
    const p = String(code).toLowerCase().split(/[-_]/)[0];
    return LOCALES[p] ? p : "en";
  }

  window.ZororoI18n = { LOCALES, t, detectLang };
